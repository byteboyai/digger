// Writes src/fixtures.ts: texts together with the top-level blocks the RUST parser (pulldown-cmark) finds in them.
// The editor's own parser is then checked against these in the webview (harness T10).
//   node scripts/make-fixtures.mjs        (needs ../parser-agreement/rust built: cargo build --release)
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { CORPUS } from "../src/corpus.ts";

const cases = [
  ["chapter corpus (all constructs, one footnote)", CORPUS],
  ["footnote, one paragraph", "正文[^1]。\n\n[^1]: 脚注内容\n\n下一段\n"],
  ["footnote, two paragraphs", "正文[^a]。\n\n[^a]: 第一段\n\n    第二段仍属于脚注\n\n下一段\n"],
  ["footnote after a list", "- 项目[^x]\n\n[^x]: 脚注\n"],
  ["footnote at the end without newline", "最后一段[^z]。\n\n[^z]: 末尾脚注"],
  ["definitions directly under each other", "[^1]: 一\n[^2]: 二\n[^3]: 三\n"],
  ["definition directly under a paragraph", "一段文字\n[^1]: 紧跟的定义\n\n后文\n"],
  ["definition with a lazy continuation line", "[^1]: 第一行\n续行没有缩进\n\n后文\n"],
  ["definition with a list inside", "[^1]: 说明:\n\n    - 甲\n    - 乙\n\n后文\n"],
  ["definition with a fenced block inside", "[^1]: 代码:\n\n    ```\n    x = 1\n    ```\n\n后文\n"],
  ["indented four spaces is code, not a definition", "    [^1]: 缩进代码\n\n后文\n"],
  ["footnotes between other blocks", "# 题\n\n甲[^1]乙[^2]\n\n[^1]: 一\n[^2]: 二\n\n> 引用\n\n[^3]: 三\n\n```\ncode\n```\n"],
];
const rustDir = path.resolve("../../parser-agreement/rust/target");
const bin = fs.readdirSync(rustDir).map((d) => path.join(rustDir, d, "release/parser-agreement-rust")).find((p) => fs.existsSync(p));
if (!bin) throw new Error("build ../parser-agreement/rust first (cargo build --release)");
const input = cases.map(([name, text], i) => JSON.stringify({ id: String(i), text })).join("\n") + "\n";
const tmp = path.join(import.meta.dirname, "..", ".fixtures-input.jsonl");
fs.writeFileSync(tmp, input);
const lines = execFileSync(bin, ["blocks", tmp], { encoding: "utf8" }).trim().split("\n").map((l) => JSON.parse(l));
fs.unlinkSync(tmp);
const out = cases.map(([name, text], i) => ({ name, text, rust: lines[i].blocks.map((b) => ({ class: b.class, startLine: b.startLine, endLine: b.endLine })) }));
fs.writeFileSync(path.join(import.meta.dirname, "../src/fixtures.ts"), `// GENERATED by scripts/make-fixtures.mjs — do not edit.\nexport const FIXTURES: { name: string; text: string; rust: { class: string; startLine: number; endLine: number }[] }[] = ${JSON.stringify(out, null, 1)};\n`);
console.log(`${out.length} fixtures; blocks per fixture: ${out.map((o) => o.rust.length).join(", ")}`);
